"""E-RL: does the encoded per-record signal survive benign downstream
use? (prereg: docs/plans/2026-10-26-emob-erl-prereg.md).

Objects: 11 audit-passing encoding finals (6 CE regenerated by lfpr,
5 passing GR from gate-g1b) + their 6 honest base starts (paired
control isolating the ft-own effect on TPR). Intervention:
fit_full(keep, seed, epochs, init=model) at lr 0.01 -- the honest
ft family's recipe -- arms ft1 x seeds {901,902} and ft3 x seed 903.
Readouts after ft: s6 (descriptive), m1, z-neggrad TPR@5% (same
fit-ensemble calibration and aux-frozen thresholds as the paper),
label-blind AUC. Retention gate preregistered.
"""
import argparse
import glob
import json
import os
import time

import numpy as np
import torch

from uw.run_ez import setup_c10
from uw.run_ey import K
from uw.run_ew3 import f_deep
from uw.run_gm import auc as rank_auc
from uw.run_r1 import load_audit
from uw.run_lfpr import (BETAS, rec, score_sets, working_point, zcal)

ARMS = (('ft1s901', 1, 901), ('ft1s902', 1, 902), ('ft3s903', 3, 903))


def probe(model, ctx, sd, sets, fit_scores, score_sd):
    sc_ = score_sets(model, sd, sets)
    out = {'s6': float(score_sd(sd)),
           'm1': float(ctx['eval_full'](sd)['m1_acc']),
           'auc_ng': float(rank_auc(sc_['mem']['neggrad'],
                                    sc_['eval']['neggrad'])), 'wp': {}}
    for ch in ('neggrad',):
        mf, ab, ef = sc_['mem'][ch], sc_['aux'][ch], sc_['eval'][ch]
        zmf = zcal(mf, [fs['mem'][ch] for fs in fit_scores])
        zab = zcal(ab, [fs['aux'][ch] for fs in fit_scores])
        zef = zcal(ef, [fs['eval'][ch] for fs in fit_scores])
        out['wp'][ch] = {str(b): working_point(zmf, zab, zef, b)
                         for b in BETAS}
    return out


def run(cli):
    device = torch.device('cuda:{}'.format(cli.gpu))
    ctx = setup_c10(device)
    model = ctx['model']
    from tools.cifar_10 import CIFAR10
    import torchvision.transforms as _tf
    tset = CIFAR10(train=False, transform=_tf.Compose([_tf.ToTensor()]))
    trset = CIFAR10(train=True, transform=_tf.Compose([_tf.ToTensor()]))
    cat_te = np.where(np.asarray(tset.cifar10.targets) == 3)[0]
    cat_tr = ctx['pool']
    fset = f_deep(cat_tr, K)
    cons = np.sort(np.random.RandomState(52801).choice(cat_te, 300,
                                                       replace=False))
    rest = np.setdiff1d(cat_te, cons)
    fresh = np.sort(np.random.RandomState(52501).choice(rest, 200,
                                                        replace=False))
    aux = np.sort(np.random.RandomState(53304).choice(
        np.setdiff1d(rest, fresh), 100, replace=False))
    ret = np.sort(np.random.RandomState(52701).choice(
        np.setdiff1d(cat_tr, fset), 30, replace=False))
    mem = (ctx['xF'], ctx['yF'])
    sets = {'mem': mem, 'aux': rec(tset, aux, device),
            'eval': rec(tset, fresh, device),
            'ret': rec(trset, ret, device)}

    fit, cal, test, c, sig, sc, q = load_audit()
    q20 = q[0.20]

    def score_sd(sd):
        return sc(ctx['eval_full'](sd))

    fit_sds = [torch.load(p, map_location=device) for p in sorted(
        glob.glob('research_outputs/uw/ew9F-20260927T001555/ckpt/'
                  'ft_k30_s*.pt'))]
    assert len(fit_sds) == 6
    fit_scores = [score_sets(model, sd, sets) for sd in fit_sds]

    e3 = sorted(glob.glob('research_outputs/uw/ex3-2*/ckpt/e3_ft_s*.pt'))
    e4 = sorted(glob.glob('research_outputs/uw/ex3-2*/ckpt/e4_ft_s*.pt'))
    pairs = [('e3-s1', e3[1]), ('e3-s3', e3[3]), ('e3-s4', e3[4]),
             ('e4-s0', e4[0]), ('e4-s1', e4[1]), ('e4-s2', e4[2])]
    fe3 = sorted(glob.glob(
        'research_outputs/uw/gate-g1b-20261007T102014/ckpt/fb_s*.pt'))
    fe4 = sorted(glob.glob(
        'research_outputs/uw/gate-g1b-20261007T104042/ckpt/fb_s*.pt'))
    ce = sorted(glob.glob(
        'research_outputs/uw/lfpr-20261009T152330/ckpt/ce_*.pt'))
    gr = fe3 + fe4
    assert len(ce) == 6, 'CE finals not found: %s' % ce
    assert len(fe3) == 3 and len(fe4) == 3, \
        'GR finals not found: %s %s' % (fe3, fe4)
    objs = [(t, 'base', p) for t, p in pairs] \
        + [(t, 'ce', p) for (t, p) in zip(
            [x[0] for x in pairs], ce)] \
        + [(t, 'gr', p) for (t, p) in zip(
            [x[0] for x in pairs], gr)]
    if cli.smoke:
        objs = objs[:1] + [o for o in objs
                           if o[0] == 'e3-s1' and o[1] == 'ce'][:1]

    rows = []
    keep = ctx['keep']
    for tag, fam, path in objs:
        sd = torch.load(path, map_location=device)
        pre = probe(model, ctx, sd, sets, fit_scores, score_sd)
        row = {'tag': tag, 'family': fam, 'path': path,
               'pre': pre, 'arms': {}}
        for arm, eps, seed in (ARMS[:1] if cli.smoke else ARMS):
            ft_sd = ctx['fit_full'](keep, seed, eps, init=sd)
            row['arms'][arm] = probe(model, ctx, ft_sd, sets, fit_scores,
                                     score_sd)
            print(' %s %s %s s6 %.2f->%.2f m1 %.4f->%.4f '
                  'zTPR5 %.2f->%.2f'
                  % (tag, fam, arm, pre['s6'], row['arms'][arm]['s6'],
                     pre['m1'], row['arms'][arm]['m1'],
                     pre['wp']['neggrad']['0.05']['tpr'],
                     row['arms'][arm]['wp']['neggrad']['0.05']['tpr']),
                  flush=True)
        rows.append(row)
        # crash-tolerant: persist progress after each object
        with open(os.path.join(cli.outdir, 'partial_rows.json'),
                  'w') as fh:
            json.dump(rows, fh, indent=1, default=float)

    # preregistered retention gate (finals with positive pre-gain)
    def tpr05(x):
        return x['wp']['neggrad']['0.05']['tpr']

    rets_ft1, rets_ft3 = [], []
    for tag, _ in pairs:
        for fam in ('ce', 'gr'):
            b_rows = [r for r in rows if r['tag'] == tag
                      and r['family'] == 'base']
            f_rows = [r for r in rows if r['tag'] == tag
                      and r['family'] == fam]
            if not b_rows or not f_rows:
                continue
            b, f_ = b_rows[0], f_rows[0]
            denom = tpr05(f_['pre']) - tpr05(b['pre'])
            if denom <= 0:
                continue
            for arm, acc in (('ft1s901', rets_ft1), ('ft3s903', rets_ft3)):
                num = (tpr05(f_['arms'][arm])
                       - tpr05(b['arms'][arm]))
                acc.append({'tag': tag, 'family': fam, 'R': num / denom})
    med1 = float(np.median([x['R'] for x in rets_ft1])) if rets_ft1 else None
    med3 = float(np.median([x['R'] for x in rets_ft3])) if rets_ft3 else None
    verdict = ('SURVIVES' if med1 is not None and med1 >= 0.5
               else 'WASHED' if med1 is not None and med1 <= 0
               else 'PARTIAL')
    out = {'generated': time.strftime('%Y-%m-%dT%H:%M:%S'),
           'q20': float(q20), 'arms': [a[0] for a in ARMS],
           'retention': {'ft1': rets_ft1, 'ft3': rets_ft3,
                         'median_ft1': med1, 'median_ft3': med3},
           'verdict': verdict, 'rows': rows}
    with open(os.path.join(cli.outdir, 'verdict.json'), 'w') as fh:
        json.dump(out, fh, indent=1, default=float)
    print('VERDICT', verdict, 'median R ft1=', med1, 'ft3=', med3,
          flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gpu', default=1, type=int)
    ap.add_argument('--outdir', default='')
    ap.add_argument('--smoke', action='store_true')
    cli = ap.parse_args()
    if not cli.outdir:
        cli.outdir = 'research_outputs/uw/%s-%s' % (
            'smoke-erl' if cli.smoke else 'erl',
            time.strftime('%Y%m%dT%H%M%S'))
    os.makedirs(cli.outdir, exist_ok=True)
    run(cli)


if __name__ == '__main__':
    main()
